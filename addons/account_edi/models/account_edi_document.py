import base64
import logging

from odoo import api, fields, models
from odoo.exceptions import LockError, UserError

_logger = logging.getLogger(__name__)

DEFAULT_BLOCKING_LEVEL = "error"


class AccountEdiDocument(models.Model):
    _name = "account.edi.document"
    _description = "Queued transmission of an account.move to a format's recipient"

    move_id = fields.Many2one(
        comodel_name="account.move",
        index=True,
        required=True,
        ondelete="cascade",
    )
    edi_format_id = fields.Many2one(
        comodel_name="account.edi.format",
        required=True,
    )
    attachment_id = fields.Many2one(
        comodel_name="ir.attachment",
        groups="base.group_system",
        help="The file generated by edi_format_id when the invoice is posted (and this document is processed).",
    )
    state = fields.Selection(
        selection=[
            ("to_send", "To Send"),
            ("sent", "Sent"),
            ("to_cancel", "To Cancel"),
            ("cancelled", "Cancelled"),
        ]
    )
    error = fields.Html(
        help="The text of the last error that happened during Electronic Invoice operation."
    )
    blocking_level = fields.Selection(
        selection=[("info", "Info"), ("warning", "Warning"), ("error", "Error")],
        help="Blocks the current operation of the document depending on the error severity:\n"
        "  * Info: the document is not blocked and everything is working as it should.\n"
        "  * Warning: there is an error that doesn't prevent the current Electronic Invoicing operation to succeed.\n"
        "  * Error: there is an error that blocks the current Electronic Invoicing operation.",
    )

    name = fields.Char(related="attachment_id.name")
    edi_format_name = fields.Char(
        related="edi_format_id.name",
        string="Format Name",
    )
    edi_content = fields.Binary(
        compute="_compute_edi_content",
        compute_sudo=True,
    )

    _unique_edi_document_by_move_by_format = models.Constraint(
        "UNIQUE(edi_format_id, move_id)",
        "Only one edi document by move by format",
    )

    @api.depends("move_id", "error", "state")
    def _compute_edi_content(self) -> None:
        for doc in self:
            res = b""
            if doc.state in ("to_send", "to_cancel"):
                move = doc.move_id
                config_errors = doc.edi_format_id._check_move_configuration(move)
                if config_errors:
                    res = base64.b64encode("\n".join(config_errors).encode("UTF-8"))
                else:
                    move_applicability = doc.edi_format_id._get_move_applicability(move)
                    if move_applicability and move_applicability.get("edi_content"):
                        res = base64.b64encode(move_applicability["edi_content"](move))
            doc.edi_content = res

    def action_export_xml(self) -> dict:
        self.check_singleton()
        return {
            "type": "ir.actions.act_url",
            "url": "/web/content/account.edi.document/%s/edi_content" % self.id,
        }

    def _prepare_jobs(self):
        to_process = {}
        for state, edi_flow in (("to_send", "post"), ("to_cancel", "cancel")):
            documents = self.filtered_domain(
                [("state", "=", state), ("blocking_level", "!=", "error")]
            )
            for edi_doc in documents:
                edi_format = edi_doc.edi_format_id
                move = edi_doc.move_id
                move_applicability = (
                    edi_doc.edi_format_id._get_move_applicability(move) or {}
                )

                batching_key = [edi_format, state, move.company_id]
                custom_batching_key = f"{edi_flow}_batching"
                if move_applicability.get(custom_batching_key):
                    batching_key += list(move_applicability[custom_batching_key](move))
                else:
                    batching_key.append(move.id)

                batch = to_process.setdefault(
                    tuple(batching_key),
                    {
                        "documents": self.env["account.edi.document"],
                        "method_to_call": move_applicability.get(edi_flow),
                    },
                )
                batch["documents"] |= edi_doc

        return list(to_process.values())

    def _postprocess_post_edi_results(self, edi_result) -> None:
        attachments_to_unlink = self.env["ir.attachment"]
        for document in self:
            move = document.move_id
            move_result = edi_result.get(move, {})
            if move_result.get("attachment"):
                old_attachment = document.sudo().attachment_id
                document.sudo().attachment_id = move_result["attachment"]
                if not old_attachment.res_model or not old_attachment.res_id:
                    attachments_to_unlink |= old_attachment
            if move_result.get("success") is True:
                document.write(
                    {
                        "state": "sent",
                        "error": False,
                        "blocking_level": False,
                    }
                )
            else:
                document.write(
                    {
                        "error": move_result.get("error", False),
                        "blocking_level": move_result.get(
                            "blocking_level", DEFAULT_BLOCKING_LEVEL
                        )
                        if "error" in move_result
                        else False,
                    }
                )

        attachments_to_unlink.sudo().unlink()

    def _postprocess_cancel_edi_results(self, edi_result) -> None:
        move_ids_to_cancel = set()
        attachments_to_unlink = self.env["ir.attachment"]
        for document in self:
            move = document.move_id
            move_result = edi_result.get(move, {})
            if move_result.get("success") is True:
                old_attachment = document.sudo().attachment_id
                document.sudo().write(
                    {
                        "state": "cancelled",
                        "error": False,
                        "attachment_id": False,
                        "blocking_level": False,
                    }
                )

                if move.state == "posted" and all(
                    doc.state == "cancelled"
                    or not doc.edi_format_id._is_web_service_required()
                    for doc in move.edi_document_ids
                ):
                    move_ids_to_cancel.add(move.id)

                if not old_attachment.res_model or not old_attachment.res_id:
                    attachments_to_unlink |= old_attachment

            else:
                document.write(
                    {
                        "error": move_result.get("error", False),
                        "blocking_level": move_result.get(
                            "blocking_level", DEFAULT_BLOCKING_LEVEL
                        )
                        if move_result.get("error")
                        else False,
                    }
                )

        if move_ids_to_cancel:
            invoices = self.env["account.move"].browse(list(move_ids_to_cancel))
            invoices.action_draft()
            invoices.action_cancel()

        attachments_to_unlink.sudo().unlink()

    @api.model
    def _process_job(self, job) -> None:

        documents = job["documents"]
        if job["method_to_call"]:
            method_to_call = job["method_to_call"]
        else:

            def method_to_call(moves):
                return {move: {"success": True} for move in moves}

        documents.edi_format_id.check_singleton()
        documents.move_id.company_id.check_singleton()
        if len({doc.state for doc in documents}) != 1:
            raise ValueError(
                "All account.edi.document of a job should have the same state"
            )

        state = documents[0].state
        documents.move_id.line_ids.flush_recordset()
        moves = documents.move_id
        if state == "to_send":
            with moves._send_only_when_ready():
                edi_result = method_to_call(moves)
            documents._postprocess_post_edi_results(edi_result)
        elif state == "to_cancel":
            edi_result = method_to_call(moves)
            documents._postprocess_cancel_edi_results(edi_result)

    def _process_documents_no_web_services(self) -> None:
        jobs = self.filtered(
            lambda d: not d.edi_format_id._is_web_service_required()
        )._prepare_jobs()
        for job in jobs:
            self._process_job(job)

    def _process_documents_web_services(self, job_count=None, with_commit=True):
        all_jobs = self.filtered(
            lambda d: d.edi_format_id._is_web_service_required()
        )._prepare_jobs()
        jobs_to_process = all_jobs[0:job_count] if job_count else all_jobs

        for job in jobs_to_process:
            documents = job["documents"]
            move_to_lock = documents.move_id
            attachments_potential_unlink = documents.sudo().attachment_id.filtered(
                lambda a: not a.res_model and not a.res_id
            )
            try:
                documents.lock_for_update()
                move_to_lock.lock_for_update()
                attachments_potential_unlink.lock_for_update()
            except LockError:
                _logger.debug(
                    "Another transaction already locked documents rows. Cannot process documents."
                )
                if not with_commit:
                    raise UserError(
                        self.env._(
                            "This document is being sent by another process already. "
                        )
                    ) from None
                continue
            self._process_job(job)
            if with_commit and len(jobs_to_process) > 1:
                self.env["ir.cron"]._commit_progress()

        return len(all_jobs) - len(jobs_to_process)

    @api.model
    def _cron_process_documents_web_services(self, job_count=None) -> None:
        edi_documents = self.search(
            [
                ("state", "in", ("to_send", "to_cancel")),
                ("move_id.state", "=", "posted"),
                ("blocking_level", "!=", "error"),
            ]
        )
        nb_remaining_jobs = edi_documents._process_documents_web_services(
            job_count=job_count
        )

        if nb_remaining_jobs > 0:
            self.env["ir.cron"]._trigger_ref("account_edi.ir_cron_edi_network")

    def _filter_edi_attachments_for_mailing(self) -> dict:
        self.check_singleton()
        attachment_sudo = self.sudo().attachment_id
        if not attachment_sudo:
            return {}
        if not (attachment_sudo.res_model and attachment_sudo.res_id):
            return {}
        if len(self.env.context.get("active_ids", [])) > 1:
            return {"attachments": [(attachment_sudo.name, attachment_sudo.datas)]}
        return {"attachment_ids": attachment_sudo.ids}
