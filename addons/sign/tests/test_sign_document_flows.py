def _pdf_text(data):
    return "".join(page.extract_text() for page in PdfReader(io.BytesIO(data)).pages)


@tagged("post_install", "-at_install")
class TestSignDocumentFlows(SignRequestCommon):
    def _template_with_items(self, *items_vals):
        template = self.env["sign.template"].create({"name": "flows"})
        document = self.env["sign.document"].create(
            {"attachment_id": self.attachment.id, "template_id": template.id}
        )
        base = {
            "required": True,
            "responsible_id": self.role_signer_1.id,
            "page": 1,
            "posX": 0.1,
            "posY": 0.1,
            "width": 0.3,
            "height": 0.03,
            "document_id": document.id,
            "type_id": self.env.ref("sign.sign_item_type_text").id,
        }
        self.env["sign.item"].create([base | vals for vals in items_vals])
        return template

    def _request(self, template, partner):
        return self.env["sign.request"].create(
            {
                "template_id": template.id,
                "reference": template.name,
                "request_item_ids": [
                    Command.create(
                        {"partner_id": partner.id, "role_id": self.role_signer_1.id}
                    )
                ],
            }
        )

    def test_unfilled_optional_item_draws_nothing_on_the_completed_document(self):
        template = self._template_with_items({"required": False})
        sign_request = self._request(template, self.partner_1)
        sign_request.request_item_ids.sudo().sign({})

        self.assertEqual(sign_request.state, "signed")
        text = _pdf_text(base64.b64decode(sign_request.completed_document_ids.file))
        self.assertNotIn("Sample generated by Odoo", text)

    def test_preview_draws_the_sample_values(self):
        template = self._template_with_items({})
        wizard = self.env["wizard.sign.template.preview"].create(
            {"template_id": template.id, "document_id": template.document_ids.id}
        )
        self.assertIn(
            "Sample generated by Odoo", _pdf_text(base64.b64decode(wizard.pdf_data))
        )

    def test_rotate_turns_the_document_until_a_request_uses_it(self):
        template = self._template_with_items({})
        document = template.document_ids
        before = PdfReader(io.BytesIO(document.attachment_id.raw)).pages[0].rotation

        self.assertTrue(document.rotate_pdf())
        after = PdfReader(io.BytesIO(document.attachment_id.raw)).pages[0].rotation
        self.assertEqual((after - before) % 360, 90)

        self._request(template, self.partner_1)
        self.assertFalse(document.rotate_pdf())

    def test_refusal_mails_name_the_refuser(self):
        sign_request = self.create_sign_request_2_roles(
            self.partner_1, self.partner_2, self.env["res.partner"]
        )
        refusing = sign_request.request_item_ids.filtered(
            lambda item: item.partner_id == self.partner_1
        )
        before = self.env["mail.mail"].search([])

        refusing.sudo()._refuse("sent", "no")

        mails = self.env["mail.mail"].search([]) - before
        self.assertEqual(len(mails), 2)
        for mail in mails:
            self.assertIn(self.partner_1.name, mail.subject)
            self.assertNotIn(self.partner_2.name, mail.subject)

    def test_shared_refusal_by_a_user_names_the_user(self):
        shared = (
            self.env["wizard.sign.template.share"]
            .create({"template_id": self.template_1_role.id, "is_shared": True})
            .sign_request_id
        )
        shared.request_item_ids.with_user(self.user_3).sudo()._refuse("shared", "nope")

        self.assertEqual(shared.state, "shared")
        refusal = shared.sign_log_ids.filtered(lambda log: log.action == "refuse")
        self.assertEqual(refusal.partner_id, self.user_3.partner_id)
        bodies = " ".join(shared.message_ids.mapped("body"))
        self.assertIn(self.user_3.name, bodies)
        self.assertNotIn("False", bodies)

    def test_pdfviewer_save_maps_only_the_items_it_created(self):
        template = self._template_with_items()
        document = template.document_ids
        vals = {
            "type_id": self.env.ref("sign.sign_item_type_text").id,
            "responsible_id": self.role_signer_1.id,
            "page": 1,
            "posX": 0.1,
            "posY": 0.1,
            "width": 0.1,
            "height": 0.02,
            "document_id": document.id,
        }
        gone = self.env["sign.item"].create(dict(vals))
        gone_id = gone.id
        gone.unlink()

        result = template.update_from_pdfviewer(
            sign_items={
                str(gone_id): dict(vals),
                "-1": dict(vals, transaction_id=-1),
            }
        )

        self.assertEqual(result, {"-1": template.sign_item_ids.id})

    def test_quick_sign_keeps_the_read_only_values(self):
        template = self._template_with_items(
            {
                "constant": True,
                "type_id": self.env.ref("sign.sign_item_type_strikethrough").id,
            },
            {
                "constant": True,
                "type_id": self.env.ref("sign.sign_item_type_date").id,
                "name": "2026-10-02",
                "posY": 0.2,
            },
        )
        wizard = self.env["wizard.sign.request.send"].create(
            {"template_id": template.id, "signer_id": self.env.user.partner_id.id}
        )
        self.assertTrue(wizard.display_download_button)

        wizard.quick_sign()

        sign_request = self.env["sign.request"].search(
            [("template_id", "=", template.id)]
        )
        self.assertEqual(sign_request.state, "signed")
        self.assertEqual(
            sorted(sign_request.request_item_ids.sign_item_value_ids.mapped("value")),
            ["2026-10-02", "striked"],
        )

    def test_selection_options_keep_the_typed_order(self):
        options = self.env["sign.item.option"]
        existing = options.browse(options.get_or_create_option_ids(["Order B"]))
        ids = options.get_or_create_option_ids(["Order C", "Order B", "Order A"])
        self.assertEqual(
            options.browse(ids).mapped("value"), ["Order C", "Order B", "Order A"]
        )
        self.assertEqual(ids[1], existing.id)

    def test_date_items_are_recognised_by_their_type(self):
        sign_request = self.create_sign_request_1_role(
            self.partner_1, self.env["res.partner"]
        )
        token = sign_request.request_item_ids.sudo().access_token
        with MockRequest(sign_request.env):
            types = Sign()._prepare_document_rendering_data(sign_request.id, token)[
                "rendering_context"
            ]["sign_item_types"]
        date_type = self.env.ref("sign.sign_item_type_date")
        self.assertEqual(
            {item_type["id"] for item_type in types if item_type["is_date"]},
            {date_type.id},
        )

    def test_a_required_role_is_refused_as_a_business_rule(self):
        with self.assertRaises(UserError):
            self.env.ref("sign.sign_item_role_default").unlink()

    def test_added_documents_are_flattened_and_numbered_after_the_last(self):
        template = self._template_with_items()
        template.document_ids.sequence = 5
        with patch(
            "odoo.addons.sign.models.sign_template.flatten_pdf",
            side_effect=lambda data: data,
        ) as flatten:
            template.update_from_attachment_data(
                [{"name": "more.pdf", "datas": self.pdf_data_64}]
            )
        self.assertEqual(flatten.call_count, 1)
        self.assertEqual(
            template.document_ids.sorted("sequence").mapped("sequence"), [5, 6]
        )

    def test_a_shared_document_takes_a_bounded_number_of_refusals(self):
        shared = (
            self.env["wizard.sign.template.share"]
            .create({"template_id": self.template_1_role.id, "is_shared": True})
            .sign_request_id
        )
        item = shared.request_item_ids.with_user(
            self.env.ref("base.public_user")
        ).sudo()
        for attempt in range(SHARED_REFUSAL_BURST):
            item._refuse(
                "shared", "no", f"Visitor {attempt}", f"v{attempt}@example.com"
            )
        with self.assertRaises(UserError):
            item._refuse("shared", "no", "One more", "more@example.com")

    def test_the_linked_record_gets_one_note_and_one_copy(self):
        record = self.env["res.partner"].create({"name": "Linked record"})
        template = self._template_with_items({"required": False})
        sign_request = self._request(template, self.partner_1)
        sign_request.reference_doc = record
        before = record.message_ids

        sign_request.request_item_ids.sudo().sign({})

        notes = (record.message_ids - before).filtered(
            lambda message: sign_request.reference in (message.body or "")
        )
        self.assertEqual(len(notes), 1)
        self.assertEqual(
            len(
                self.env["ir.attachment"].search(
                    [("res_model", "=", "res.partner"), ("res_id", "=", record.id)]
                )
            ),
            len(sign_request.completed_document_ids),
        )


@tagged("post_install", "-at_install")
class TestSignDocumentRoutes(TestSignControllerCommon):
    def test_refusing_by_link_posts_one_message(self):
        sign_request = self.create_sign_request_1_role(
            self.partner_1, self.env["res.partner"]
        )
        token = sign_request.request_item_ids.sudo().access_token
        before = sign_request.message_ids
        self.authenticate(None, None)

        self._json_url_open(
            f"/sign/refuse/{sign_request.id}/{token}", {"refusal_reason": "x"}
        )

        refusals = (sign_request.message_ids - before).filtered(
            lambda message: "refused" in message.body or "canceled by" in message.body
        )
        self.assertEqual(len(refusals), 1)
        self.assertEqual(sign_request.state, "canceled")

    def test_malformed_link_expiry_is_refused_not_an_error(self):
        sign_request = self.create_sign_request_1_role(
            self.partner_1, self.env["res.partner"]
        )
        token = sign_request.request_item_ids.sudo().access_token
        self.authenticate(None, None)

        response = self.url_open(
            f"/sign/document/mail/{sign_request.id}/{token}?timestamp=abc&exp=def"
        )

        self.assertEqual(response.status_code, 403)
