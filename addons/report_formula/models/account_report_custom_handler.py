import io
import zipfile
from collections.abc import Collection, Mapping
from typing import Any, Protocol, TypedDict

from odoo import models


class LineExpansion(TypedDict):
    lines: list[dict[str, Any]]
    offset_increment: int
    has_more: bool
    progress: dict[str, Any] | None


class ReportLineBuilder(Protocol):
    def __call__(
        self,
        report: models.BaseModel,
        options: dict[str, Any],
        line_key: Any,
        line_values: Any,
        /,
        *,
        parent_line_id: str,
    ) -> dict[str, Any]: ...


class AccountReportFileDownloadException(Exception):
    def __init__(self, errors, content=None) -> None:
        super().__init__()
        self.errors = errors
        self.content = content


class AccountReportCustomHandler(models.AbstractModel):
    _name = "report.formula.custom.handler"
    _description = "Formula Report Custom Handler"

    def _dynamic_lines_generator(
        self, report, options, all_column_groups_expression_totals, warnings=None
    ):
        return []

    def _prepare_sequenced_lines_with_total(
        self,
        lines: list[dict[str, Any]],
        total_line: dict[str, Any] | None,
    ) -> list[tuple[int, dict[str, Any]]]:
        """Give dynamic lines their default sequence, followed by an optional total."""
        if total_line:
            lines = [*lines, total_line]
        return [(0, line) for line in lines]

    def _prepare_line_expansion(
        self,
        report: models.BaseModel,
        options: dict[str, Any],
        line_dict_id: str,
        progress: dict[str, Any] | None,
        lines_values: Mapping[Any, Any],
        *,
        report_line_method: ReportLineBuilder,
    ) -> LineExpansion:
        lines = []
        has_more = False
        treated_results_count = 0
        next_progress = progress

        for line_key, line_values in lines_values.items():
            if (
                options["export_mode"] != "print"
                and report["load_more_limit"]
                and treated_results_count == report["load_more_limit"]
            ):
                # We loaded one more than the limit on purpose: this way we know we need a "load more" line
                has_more = True
                break

            new_line = report_line_method(
                report, options, line_key, line_values, parent_line_id=line_dict_id
            )
            lines.append(new_line)
            next_progress = {
                column["column_group_key"]: line_col.get("no_format", 0)
                for column, line_col in zip(
                    options["columns"], new_line["columns"], strict=False
                )
                if column["expression_label"] == "balance"
            }
            treated_results_count += 1

        return {
            "lines": lines,
            "offset_increment": treated_results_count,
            "has_more": has_more,
            "progress": next_progress,
        }

    def _caret_options_initializer(self):
        return self.env["report.formula"]._caret_options_initializer_default()

    def _custom_options_initializer(self, report, options, previous_options):
        pass

    def _custom_line_postprocessor(self, report, options, lines):
        return lines

    def _custom_groupby_line_completer(
        self, report, options, line_dict, current_groupby
    ):
        """Postprocesses the dict generated by the group_by_line, to customize its content."""

    def _custom_unfold_all_batch_data_generator(
        self, report, options, lines_to_expand_by_function
    ):
        return

    def _get_custom_groupby_map(self) -> dict:
        return {}

    def _customize_warnings(
        self, report, options, all_column_groups_expression_totals, warnings
    ):
        """To be overridden to add report-specific warnings in the warnings dictionary.
        When a root report defines something in this function, its variants without any custom handler will also call the root report's
        _customize_warnings function. This can hence be used to share warnings between all variants.

        Should only be used when necessary, _dynamic_lines_generator is preferred.
        """

    def _get_line_columns(self, report, options, data):
        line_columns = []
        for column in options["columns"]:
            col_value = data[column["column_group_key"]].get(column["expression_label"])
            line_columns.append(
                report._prepare_column_dict(
                    col_value=col_value or "",
                    col_data=column,
                    options=options,
                )
            )
        return line_columns

    def _get_zip_export(
        self, file_name: str, files: Collection[tuple[str, str | bytes]]
    ) -> dict:
        with io.BytesIO() as buffer:
            with zipfile.ZipFile(
                buffer, "w", compression=zipfile.ZIP_DEFLATED
            ) as zip_file:
                for name, content in files:
                    zip_file.writestr(name, content)
            return {
                "file_name": file_name,
                "file_content": buffer.getvalue(),
                "file_type": "zip",
            }
