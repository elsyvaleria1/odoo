import pytest

from odoo.tools.method_data import rewrite_model_method_references


@pytest.mark.parametrize(
    ("name", "source_name"),
    [
        ("检查_host", "检查_host"),
        ("check_host", "ｃｈｅｃｋ_host"),
        ("check_host", "check_ｈｏｓｔ"),
        ("check_host", "check＿host"),
    ],
)
def test_method_reference_rewrites_follow_python_identifier_normalization(
    name, source_name
):
    source = (
        "# café: preserve the source spelling " + source_name + "\n"
        'guard = env["ir.egress"]\n'
        f'guard . {source_name}("1.1.1.1", 443)\n'
        f'text = "{source_name}"\n'
    )
    result = rewrite_model_method_references(
        source,
        None,
        {},
        model_method_renames={("ir.egress", name): "get_permitted_host_addresses"},
    )
    expected = source.replace(
        f"guard . {source_name}", "guard . get_permitted_host_addresses"
    )
    assert result.code == expected
    assert not result.unresolved
    calls = []

    class Guard:
        def get_permitted_host_addresses(self, host, port):
            calls.append((host, port))

    exec(  # noqa: S102 -- Executes only the fixed source generated by this regression test.
        compile(result.code, "stored method rewrite", "exec"),
        {"env": {"ir.egress": Guard()}},
    )
    assert calls == [("1.1.1.1", 443)]


def test_computed_reflection_names_on_a_renamed_owner_are_reported_for_review():
    result = rewrite_model_method_references(
        'getattr(env["ir.egress"], dynamic_method)()',
        None,
        {},
        model_method_renames={
            ("ir.egress", "check_host"): "get_permitted_host_addresses"
        },
    )
    assert result.unresolved == frozenset({("check_host", 1)})
